int main() {
    constexpr uint32_t rows = 17;
    constexpr uint32_t channels = 8;
    constexpr uint32_t capacity = rows + 5;

    ggml_backend_t backend = ggml_backend_metal_init();
    if (backend == nullptr) {
        return 1;
    }
    ggml_init_params params = { ggml_tensor_overhead() * 9, nullptr, true };
    ggml_context * ctx = ggml_init(params);
    if (ctx == nullptr) {
        ggml_backend_free(backend);
        return 2;
    }
    ggml_tensor * row_major16 = ggml_new_tensor_2d(ctx, GGML_TYPE_F16, channels, capacity);
    ggml_tensor * row_major16_packed = ggml_new_tensor_2d(ctx, GGML_TYPE_F16, channels, capacity);
    ggml_tensor * transposed16 = ggml_new_tensor_2d(ctx, GGML_TYPE_F16, capacity, channels);
    ggml_tensor * row_major32 = ggml_new_tensor_2d(ctx, GGML_TYPE_F32, channels, capacity);
    ggml_tensor * transposed32 = ggml_new_tensor_2d(ctx, GGML_TYPE_F32, capacity, channels);
    constexpr uint32_t quant_channels = 32;
    ggml_tensor * row_major_quant_f16 = ggml_new_tensor_2d(ctx, GGML_TYPE_F16, quant_channels, capacity);
    ggml_tensor * row_major_q8 = ggml_new_tensor_2d(ctx, GGML_TYPE_Q8_0, quant_channels, capacity);
    ggml_tensor * row_major_q4 = ggml_new_tensor_2d(ctx, GGML_TYPE_Q4_0, quant_channels, capacity);
    constexpr uint32_t multi_capacity = rows * 2 + 5;
    ggml_tensor * multi_tile = ggml_new_tensor_2d(ctx, GGML_TYPE_F16, channels, multi_capacity);
    ggml_backend_buffer_t buffer = ggml_backend_alloc_ctx_tensors(ctx, backend);
    if (buffer == nullptr) {
        ggml_free(ctx);
        ggml_backend_free(backend);
        return 3;
    }
    const auto finish = [&](int status) {
        ggml_backend_buffer_free(buffer);
        ggml_free(ctx);
        ggml_backend_free(backend);
        return status;
    };

    std::vector<uint32_t> cells(rows);
    for (uint32_t row = 0; row < rows; ++row) {
        cells[row] = capacity - 1 - row;
    }
    const ggml_backend_cachegen_tile tile16 = { encoded16, sizeof(encoded16), 0, rows };
    const ggml_backend_cachegen_tile tile16_packed = { encoded16_packed, sizeof(encoded16_packed), 0, rows };
    const ggml_backend_cachegen_tile tile32 = { encoded32, sizeof(encoded32), 0, rows };
    const std::vector<uint8_t> encoded_quant = repeat_cachegen_channels(encoded16, sizeof(encoded16), 4);
    const ggml_backend_cachegen_tile tile_quant = { encoded_quant.data(), encoded_quant.size(), 0, rows };
    const ggml_backend_cachegen_tile multi_tiles[] = {
        { encoded16, sizeof(encoded16), 0, rows },
        { encoded32, sizeof(encoded32), rows, rows },
    };
    std::vector<uint32_t> multi_cells(rows * 2);
    for (uint32_t row = 0; row < rows * 2; ++row) {
        multi_cells[row] = multi_capacity - 1 - row;
    }
    const ggml_backend_cachegen_job jobs[] = {
        { row_major16, &tile16, 1, cells.data(), cells.size(), channels, channels * 2, 2 },
        { row_major16_packed, &tile16_packed, 1, cells.data(), cells.size(), channels, channels * 2, 2 },
        { transposed16, &tile16, 1, cells.data(), cells.size(), channels, 2, capacity * 2 },
        { row_major32, &tile32, 1, cells.data(), cells.size(), channels, channels * 4, 4 },
        { transposed32, &tile32, 1, cells.data(), cells.size(), channels, 4, capacity * 4 },
        { multi_tile, multi_tiles, 2, multi_cells.data(), multi_cells.size(), channels, channels * 2, 2 },
        { row_major_quant_f16, &tile_quant, 1, cells.data(), cells.size(), quant_channels, quant_channels * 2, 2 },
        { row_major_q8, &tile_quant, 1, cells.data(), cells.size(), quant_channels, 34, 34 },
        { row_major_q4, &tile_quant, 1, cells.data(), cells.size(), quant_channels, 18, 18 },
    };
    ggml_backend_dev_t device = ggml_backend_get_device(backend);
    auto decode = reinterpret_cast<ggml_backend_cachegen_decode_t>(
        ggml_backend_reg_get_proc_address(
            ggml_backend_dev_backend_reg(device), "ggml_backend_cachegen_decode"));
    if (decode == nullptr) {
        return finish(4);
    }
    char error[256] = {};
    if (!decode(jobs, 9, error, sizeof(error))) {
        return finish(5);
    }
    ggml_backend_cachegen_job invalid_job = jobs[0];
    invalid_job.token_stride = UINT64_MAX;
    if (decode(&invalid_job, 1, error, sizeof(error))) {
        return finish(8);
    }
    std::vector<uint8_t> invalid_packed(encoded16_packed, encoded16_packed + sizeof(encoded16_packed));
    invalid_packed[5] = 5;
    const ggml_backend_cachegen_tile invalid_packed_tile = {
        invalid_packed.data(), invalid_packed.size(), 0, rows,
    };
    ggml_backend_cachegen_job invalid_packed_job = jobs[1];
    invalid_packed_job.tiles = &invalid_packed_tile;
    if (decode(&invalid_packed_job, 1, error, sizeof(error))) {
        return finish(14);
    }

    const auto check_fixture = [&](ggml_tensor * row_major, ggml_tensor * transposed,
                                   const uint8_t * expected, int status) {
        std::vector<uint8_t> row_bytes(ggml_nbytes(row_major));
        std::vector<uint8_t> transposed_bytes(ggml_nbytes(transposed));
        ggml_backend_tensor_get(row_major, row_bytes.data(), 0, row_bytes.size());
        ggml_backend_tensor_get(transposed, transposed_bytes.data(), 0, transposed_bytes.size());
        for (uint32_t row = 0; row < rows; ++row) {
            if (std::memcmp(
                    row_bytes.data() + static_cast<size_t>(cells[row]) * channels * 2,
                    expected + static_cast<size_t>(row) * channels * 2,
                    channels * 2) != 0) {
                return status;
            }
            for (uint32_t channel = 0; channel < channels; ++channel) {
                if (std::memcmp(
                        transposed_bytes.data() + (cells[row] + static_cast<size_t>(channel) * capacity) * 2,
                        expected + (static_cast<size_t>(row) * channels + channel) * 2,
                        2) != 0) {
                    return status;
                }
            }
        }
        return 0;
    };
    if (const int status = check_fixture(row_major16, transposed16, expected16, 6)) {
        return finish(status);
    }
    std::vector<uint8_t> packed16_bytes(ggml_nbytes(row_major16_packed));
    ggml_backend_tensor_get(row_major16_packed, packed16_bytes.data(), 0, packed16_bytes.size());
    for (uint32_t row = 0; row < rows; ++row) {
        if (std::memcmp(
                packed16_bytes.data() + static_cast<size_t>(cells[row]) * channels * 2,
                expected16 + static_cast<size_t>(row) * channels * 2,
                channels * 2) != 0) {
            return finish(13);
        }
    }
    std::vector<float> expected32_f32(rows * channels);
    for (size_t i = 0; i < expected32_f32.size(); ++i) {
        uint16_t bits;
        std::memcpy(&bits, expected32 + i * sizeof(bits), sizeof(bits));
        expected32_f32[i] = ggml_fp16_to_fp32(bits);
    }
    std::vector<float> row32(ggml_nelements(row_major32));
    std::vector<float> transposed32_values(ggml_nelements(transposed32));
    ggml_backend_tensor_get(row_major32, row32.data(), 0, ggml_nbytes(row_major32));
    ggml_backend_tensor_get(transposed32, transposed32_values.data(), 0, ggml_nbytes(transposed32));
    for (uint32_t row = 0; row < rows; ++row) {
        for (uint32_t channel = 0; channel < channels; ++channel) {
            const float expected = expected32_f32[static_cast<size_t>(row) * channels + channel];
            if (row32[static_cast<size_t>(cells[row]) * channels + channel] != expected ||
                    transposed32_values[cells[row] + static_cast<size_t>(channel) * capacity] != expected) {
                return finish(7);
            }
        }
    }
    std::vector<uint8_t> multi_bytes(ggml_nbytes(multi_tile));
    ggml_backend_tensor_get(multi_tile, multi_bytes.data(), 0, multi_bytes.size());
    const uint8_t * expected_tiles[] = { expected16, expected32 };
    for (uint32_t tile = 0; tile < 2; ++tile) {
        for (uint32_t row = 0; row < rows; ++row) {
            const uint32_t source_row = tile * rows + row;
            if (std::memcmp(
                    multi_bytes.data() + static_cast<size_t>(multi_cells[source_row]) * channels * 2,
                    expected_tiles[tile] + static_cast<size_t>(row) * channels * 2,
                    channels * 2) != 0) {
                return finish(9);
            }
        }
    }
    std::vector<float> quant_source(rows * quant_channels);
    for (uint32_t row = 0; row < rows; ++row) {
        for (uint32_t channel = 0; channel < quant_channels; ++channel) {
            uint16_t bits;
            const uint32_t source_channel = (channel % channels + channel / channels) % channels;
            std::memcpy(&bits, expected16 + (row * channels + source_channel) * sizeof(bits), sizeof(bits));
            quant_source[row * quant_channels + channel] = ggml_fp16_to_fp32(bits);
        }
    }
    std::vector<uint8_t> quant_f16_bytes(ggml_nbytes(row_major_quant_f16));
    ggml_backend_tensor_get(row_major_quant_f16, quant_f16_bytes.data(), 0, quant_f16_bytes.size());
    for (uint32_t row = 0; row < rows; ++row) {
        for (uint32_t channel = 0; channel < quant_channels; ++channel) {
            if (std::memcmp(quant_f16_bytes.data() + ((size_t) cells[row] * quant_channels + channel) * 2,
                            expected16 + ((size_t) row * channels +
                                (channel % channels + channel / channels) % channels) * 2, 2) != 0) {
                return finish(12);
            }
        }
    }
    const auto check_quantized = [&](ggml_tensor * tensor, ggml_type type, size_t row_bytes, int status) {
        std::vector<uint8_t> expected(rows * row_bytes);
        if (ggml_quantize_chunk(type, quant_source.data(), expected.data(), 0, rows, quant_channels, nullptr) !=
                expected.size()) {
            return status;
        }
        std::vector<uint8_t> actual(ggml_nbytes(tensor));
        ggml_backend_tensor_get(tensor, actual.data(), 0, actual.size());
        for (uint32_t row = 0; row < rows; ++row) {
            if (std::memcmp(actual.data() + (size_t) cells[row] * row_bytes,
                            expected.data() + (size_t) row * row_bytes, row_bytes) != 0) {
                return status;
            }
        }
        return 0;
    };
    if (const int status = check_quantized(row_major_q8, GGML_TYPE_Q8_0, 34, 10)) {
        return finish(status);
    }
    if (const int status = check_quantized(row_major_q4, GGML_TYPE_Q4_0, 18, 11)) {
        return finish(status);
    }
    return finish(0);
}
