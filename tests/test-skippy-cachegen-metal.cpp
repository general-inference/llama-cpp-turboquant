static std::vector<uint8_t> repeat_cachegen_channels(
        const uint8_t * payload, size_t payload_bytes, uint32_t repeats) {
    const uint32_t rows = (uint32_t) payload[6] | (uint32_t) payload[7] << 8;
    const uint32_t channels = (uint32_t) payload[8] | (uint32_t) payload[9] << 8 |
        (uint32_t) payload[10] << 16 | (uint32_t) payload[11] << 24;
    const size_t cdf_offset = 16 + (size_t) rows * sizeof(float);
    const size_t cdf_bytes = (size_t) channels * 33 * sizeof(uint16_t);
    const size_t lengths_offset = cdf_offset + cdf_bytes;
    const size_t lengths_bytes = (size_t) channels * sizeof(uint16_t);
    const size_t streams_offset = lengths_offset + lengths_bytes;
    std::vector<size_t> stream_offsets(channels + 1);
    for (uint32_t channel = 0; channel < channels; ++channel) {
        const size_t offset = lengths_offset + (size_t) channel * sizeof(uint16_t);
        stream_offsets[channel + 1] = stream_offsets[channel] +
            ((uint32_t) payload[offset] | (uint32_t) payload[offset + 1] << 8);
    }
    std::vector<uint8_t> result(payload, payload + cdf_offset);
    for (uint32_t repeat = 0; repeat < repeats; ++repeat) {
        for (uint32_t channel = 0; channel < channels; ++channel) {
            const uint32_t source = (channel + repeat) % channels;
            result.insert(result.end(), payload + cdf_offset + (size_t) source * 33 * sizeof(uint16_t),
                          payload + cdf_offset + (size_t) (source + 1) * 33 * sizeof(uint16_t));
        }
    }
    for (uint32_t repeat = 0; repeat < repeats; ++repeat) {
        for (uint32_t channel = 0; channel < channels; ++channel) {
            const uint32_t source = (channel + repeat) % channels;
            result.insert(result.end(), payload + lengths_offset + (size_t) source * sizeof(uint16_t),
                          payload + lengths_offset + (size_t) (source + 1) * sizeof(uint16_t));
        }
    }
    for (uint32_t repeat = 0; repeat < repeats; ++repeat) {
        for (uint32_t channel = 0; channel < channels; ++channel) {
            const uint32_t source = (channel + repeat) % channels;
            result.insert(result.end(), payload + streams_offset + stream_offsets[source],
                          payload + streams_offset + stream_offsets[source + 1]);
        }
    }
    const uint32_t output_channels = channels * repeats;
    const uint32_t output_stream_bytes = (uint32_t) (payload_bytes - streams_offset) * repeats;
    for (uint32_t byte = 0; byte < 4; ++byte) {
        result[8 + byte] = uint8_t(output_channels >> (byte * 8));
        result[12 + byte] = uint8_t(output_stream_bytes >> (byte * 8));
    }
    return result;
}

